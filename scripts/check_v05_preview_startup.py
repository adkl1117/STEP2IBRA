"""Bounded V0.5 preview startup/import verifier (coordinator runtime helper).

Launches the **actual** ``FreeCAD.exe`` against the preview profile and asserts the
installed preview plugin is the one FreeCAD really imported.  It deliberately does
**not** monkeypatch the user home or pin ``sys.path``/modules: FreeCAD resolves its
own module paths, so a default-distribution or older shadowing copy of the plugin is
detected instead of being masked.

Isolation (originals are never written):

* ``FREECAD_USER_HOME`` is the real preview profile, so ``Mod/`` is resolved by
  FreeCAD itself.
* ``user.cfg`` / ``system.cfg`` are **cloned into** ``--out/config`` and passed with
  ``-u`` / ``-s``, so FreeCAD must not touch the preview profile's originals.
* The launcher command file's declared ``FREECAD_EXE`` / ``FREECAD_USER_HOME`` are
  read and reported, not re-interpreted.
* On timeout only the owned ``FreeCAD.exe`` child is terminated.

A verification macro is generated into ``--out`` (a generated test artifact) and
passed as the positional file argument.  The macro activates ``KratosIBRAWorkbench``,
imports ``kratos_iga``, and records JSON checks, module file paths and the startup log.

    python scripts/check_v05_preview_startup.py \
        --preview-root runtime/v0.5-preview \
        --out runtime/v0.5-preview-verify \
        --timeout 45
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent                                        # STEP2IBRA-publish
WORKSPACE = ROOT.parent
DEFAULT_PREVIEW = WORKSPACE / "runtime/v0.5-preview"
DEFAULT_FREECAD = WORKSPACE / "FreeCAD/FreeCAD_1.1.3-Windows-x86_64-py311/FreeCAD.exe"
LAUNCHER_NAME = "Start-FreeCAD-V0.5-Preview.cmd"
MACRO_NAME = "verify_v05_startup.FCMacro"

MACRO = r'''# Generated by scripts/check_v05_preview_startup.py. Bounded V0.5 preview startup
# verification; runs inside the real FreeCAD GUI and writes verify_result.json.
import json
import os
import sys
import time
import traceback
from pathlib import Path

OUT = Path(os.environ["IBRA_V05_VERIFY_OUT"])
PREVIEW_ROOT = Path(os.environ["IBRA_V05_PREVIEW_ROOT"])
PLUGIN_ROOT = Path(os.environ["IBRA_V05_PLUGIN_ROOT"])
TWO_PATCH = os.environ.get("IBRA_V05_TWO_PATCH") == "1"
RESULT = OUT / "verify_result.json"

checks = []
module_paths = {}
notes = {}


def norm(value):
    return str(Path(value).resolve()).replace("\\", "/").lower()


def check(name, ok, detail=None, optional=False):
    entry = {"name": name, "ok": bool(ok), "optional": bool(optional)}
    if detail is not None:
        entry["detail"] = detail
    checks.append(entry)
    return entry


def summary():
    return {
        "macro": "verify_v05_startup.FCMacro",
        "preview_root": str(PREVIEW_ROOT),
        "plugin_root": str(PLUGIN_ROOT),
        "app_user_app_data_dir": module_paths.get("app_user_app_data_dir"),
        "module_paths": module_paths,
        "notes": notes,
        "checks": checks,
        "error": None,
    }


def run():
    import FreeCAD as App
    import FreeCADGui as Gui

    module_paths["freecad_version"] = [str(part) for part in App.Version()]
    module_paths["app_user_app_data_dir"] = App.getUserAppDataDir()
    check("app_user_app_data_dir",
          norm(App.getUserAppDataDir()) == norm(PREVIEW_ROOT / "profile"),
          App.getUserAppDataDir())

    try:
        Gui.updateGui()
        Gui.activateWorkbench("KratosIBRAWorkbench")
        Gui.updateGui()
    except Exception:
        notes["activate_workbench_error"] = traceback.format_exc()
    workbench = Gui.activeWorkbench()
    module_paths["active_workbench"] = type(workbench).__name__
    module_paths["active_workbench_module"] = type(workbench).__module__
    check("workbench_activated", type(workbench).__name__ == "KratosIBRAWorkbench",
          type(workbench).__name__)
    check("workbench_menu_text",
          getattr(workbench, "MenuText", "") == "IBRA Preprocessor for Kratos",
          getattr(workbench, "MenuText", None))

    import kratos_iga
    import kratos_iga.gui as gui
    import kratos_iga.interaction as interaction
    import kratos_iga.settings as settings
    import kratos_iga.workbench as workbench_module

    modules = {"kratos_iga": kratos_iga, "kratos_iga.gui": gui,
               "kratos_iga.interaction": interaction, "kratos_iga.settings": settings,
               "kratos_iga.workbench": workbench_module}
    for name, module in modules.items():
        module_paths[name] = getattr(module, "__file__", None)

    installed = norm(PLUGIN_ROOT)
    check("package_installed_preview_path",
          norm(kratos_iga.__file__).startswith(installed), kratos_iga.__file__)
    check("version_0_5_0", getattr(kratos_iga, "__version__", None) == "0.5.0",
          getattr(kratos_iga, "__version__", None))
    for name, module in modules.items():
        check(name + "_from_preview_path",
              getattr(module, "__file__", None) is not None
              and norm(module.__file__).startswith(installed),
              getattr(module, "__file__", None))

    shadowed = sorted(name for name, module in sys.modules.items()
                      if (name == "kratos_iga" or name.startswith("kratos_iga."))
                      and getattr(module, "__file__", None)
                      and not norm(module.__file__).startswith(installed))
    notes["shadowed_modules"] = shadowed
    notes["sys_path_plugin_entries"] = [
        entry for entry in sys.path if "KratosIBRA" in entry or entry.endswith("Mod")]
    check("no_shadowed_plugin_modules", not shadowed, shadowed)

    # V0.5 interaction module: hover modes, coupling-only, new mouse buttons.
    check("interaction_hover_modes",
          tuple(interaction.HOVER_MODES) == ("all", "edge", "patch", "coupling"),
          list(interaction.HOVER_MODES))
    check("interaction_coupling_only",
          interaction.KIND_COUPLING == "coupling"
          and interaction.hover_mode_allows("coupling", interaction.KIND_COUPLING)
          and not interaction.hover_mode_allows("patch", interaction.KIND_COUPLING)
          and hasattr(interaction, "VisibilityController"),
          {"kind": interaction.KIND_COUPLING,
           "visibility_controller": hasattr(interaction, "VisibilityController")})
    check("interaction_coupling_only_button",
          callable(getattr(gui.Panel, "toggle_coupling_visibility", None)),
          hasattr(gui.Panel, "toggle_coupling_visibility"))
    check("interaction_mouse_actions",
          all(hasattr(interaction, name) for name in
              ("middle_action", "middle_ownership", "MIDDLE_CONFIRM",
               "MIDDLE_OWN_PRESS", "MIDDLE_PASS", "classify_coin_event"))
          and interaction.middle_action(phase="release", owned=True, has_press=True,
                                        mapped=(1, 1))[0] == interaction.MIDDLE_CONFIRM,
          None)

    class _EventType:
        BUTTON1 = 1
        BUTTON2 = 2
        BUTTON3 = 3
        DOWN = 0

        def getName(self):
            return "SoMouseButtonEvent"

    class _MouseEvent:
        def __init__(self, button):
            self._button = button

        def getTypeId(self):
            return _EventType()

        def getState(self):
            return _EventType.DOWN

        def getButton(self):
            return self._button

        def getPosition(self):
            return (4, 5)

    buttons = {name: interaction.classify_coin_event(_MouseEvent(value))
               for name, value in (("left", 1), ("middle", 3), ("right", 2))}
    check("mouse_button_mapping",
          buttons["left"]["action"] == "left"
          and buttons["middle"]["action"] == "middle"
          and buttons["middle"]["consume"] is True
          and buttons["right"]["action"] == "right"
          and buttons["right"]["consume"] is False,
          buttons)

    machine = interaction.SelectionMachine()
    check("interaction_selection_machine",
          machine.set_hover_mode("coupling").ok
          and machine.set_hover_mode("bogus").refused == "hover_mode",
          None)

    # Backend fields must point at the installed preview plugin, not a checkout.
    plugin_dir = Path(kratos_iga.__file__).resolve().parents[1]
    module_paths["plugin_dir_from_package"] = str(plugin_dir)
    backend = settings.load_settings(App.getUserAppDataDir(), plugin_dir)
    notes["backend_settings"] = backend
    pipeline = Path(backend["pipeline_root"])
    check("backend_pipeline_root_installed_path",
          norm(pipeline) == norm(PLUGIN_ROOT / "backend")
          and (pipeline / "cad_pipeline" / "api.py").is_file(),
          backend["pipeline_root"])
    check("backend_python_exists", Path(backend["backend_python"]).is_file(),
          backend["backend_python"])
    check("backend_work_dir_in_preview_profile",
          norm(backend["work_dir"]).startswith(norm(PREVIEW_ROOT / "profile")),
          backend["work_dir"])
    check("backend_config_file_installed_path",
          (plugin_dir / "backend_config.json").is_file(),
          str(plugin_dir / "backend_config.json"))

    examples = {
        "cantilever": plugin_dir / "examples/v0_5_cantilever/cantilever.ibra-project.json",
        "two_patch": plugin_dir / "examples/two_patch/two_patch_shell.ibra-project.json",
        "perforated_plate": plugin_dir
        / "examples/perforated_plate/perforated_plate.ibra-project.json",
    }
    notes["examples"] = {name: str(path) for name, path in examples.items()}
    check("examples_three_installed", all(path.is_file() for path in examples.values()),
          {name: path.is_file() for name, path in examples.items()})

    if TWO_PATCH:
        two_patch = {}
        try:
            gui.show_panel()
            panel = getattr(gui, "_panel", None)
            if panel is None:
                raise RuntimeError("the IBRA panel did not start")
            # In-memory only: the configured work directory and saved settings are untouched.
            panel.work_dir = OUT / "work"
            panel.work_dir.mkdir(parents=True, exist_ok=True)
            panel.load_project(str(examples["two_patch"]))
            deadline = time.monotonic() + 20.0
            while time.monotonic() < deadline:
                Gui.updateGui()
                if (panel.process is None and getattr(panel, "pending_project", None) is None
                        and panel.entities):
                    break
                time.sleep(0.1)
            faces = sorted({ident for (kind, ident) in panel.entities if kind == "face"})
            couplings = len((getattr(panel, "project", None) or {}).get("couplings", []))
            two_patch = {"faces": faces, "face_count": len(faces),
                         "coupling_count": couplings, "work_dir": str(panel.work_dir)}
        except Exception:
            two_patch = {"error": traceback.format_exc()}
        notes["two_patch"] = two_patch
        check("two_patch_load_two_faces_one_coupling",
              two_patch.get("face_count") == 2 and two_patch.get("coupling_count") == 1,
              two_patch, optional=True)


def main():
    try:
        run()
    except Exception:
        notes["fatal_error"] = traceback.format_exc()
    payload = summary()
    payload["error"] = notes.get("fatal_error")
    RESULT.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    try:
        import FreeCAD as App
        App.quit()
    except Exception:
        pass


try:
    main()
except Exception:
    traceback.print_exc()
'''


def read_launcher(path: Path) -> dict:
    info: dict = {"path": str(path), "exists": path.is_file()}
    if not path.is_file():
        return info
    text = path.read_text(encoding="utf-8", errors="replace")
    for key in ("FREECAD_EXE", "FREECAD_USER_HOME"):
        match = re.search(r'set\s+"?' + key + r'=(.*?)"?\s*$', text, re.M)
        info[key.lower()] = match.group(1).strip().strip('"') if match else None
    return info


def stop_owned(proc: subprocess.Popen) -> None:
    """Terminate only the FreeCAD process this helper owns."""
    if proc.poll() is not None:
        return
    proc.terminate()
    try:
        proc.wait(timeout=5)
    except subprocess.TimeoutExpired:
        proc.kill()
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass


def run_freecad(exe: Path, macro: Path, user_cfg: Path, system_cfg: Path, env: dict,
                out: Path, result_file: Path, log_path: Path, timeout: float) -> dict:
    # The portable distribution's outer launcher detaches bin/freecad.exe, then
    # exits. Own the actual GUI child so the deadline and cleanup remain effective.
    declared_exe = exe
    inner_exe = exe.parent / "bin" / exe.name
    if inner_exe.is_file():
        exe = inner_exe
        env = dict(env)
        env["PATH"] = str(exe.parent) + os.pathsep + env.get("PATH", "")
    command = [str(exe), "-u", str(user_cfg), "-s", str(system_cfg), str(macro)]
    deadline = time.monotonic() + timeout
    result_seen_at = None
    timed_out = False
    terminated_after_result = False
    with log_path.open("wb") as log:
        proc = subprocess.Popen(command, env=env, cwd=str(out), stdin=subprocess.DEVNULL,
                                stdout=log, stderr=subprocess.STDOUT)
        while True:
            if proc.poll() is not None:
                break
            if result_seen_at is None and result_file.is_file():
                try:
                    json.loads(result_file.read_text(encoding="utf-8"))
                    result_seen_at = time.monotonic()
                except Exception:
                    pass
            now = time.monotonic()
            if result_seen_at is not None and now - result_seen_at > 5.0:
                terminated_after_result = True
                stop_owned(proc)
                break
            if now > deadline:
                timed_out = True
                stop_owned(proc)
                break
            time.sleep(0.2)
    return {"command": command, "declared_exe": str(declared_exe),
            "actual_gui_exe": str(exe), "exit": proc.poll(), "timed_out": timed_out,
            "terminated_after_result": terminated_after_result,
            "result_seen": result_file.is_file()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--preview-root", default=str(DEFAULT_PREVIEW),
                        help="Preview root containing profile/ (default: %(default)s)")
    parser.add_argument("--out", required=True, help="New output directory under the repo runtime.")
    parser.add_argument("--timeout", type=float, default=45.0, help="Hard child timeout in seconds.")
    parser.add_argument("--freecad-exe", default="", help="Override the launcher's FreeCAD.exe.")
    parser.add_argument("--two-patch", action="store_true",
                        help="Also really load examples/two_patch into the panel (optional check).")
    args = parser.parse_args()

    preview_root = Path(args.preview_root).resolve()
    out = Path(args.out).resolve()
    plugin_root = preview_root / "profile" / "Mod" / "KratosIBRA"
    profile = preview_root / "profile"
    launcher = read_launcher(preview_root / LAUNCHER_NAME)

    def fail(message: str, code: int = 2) -> int:
        print(json.dumps({"host_ok": False, "error": message,
                          "preview_root": str(preview_root), "out": str(out)},
                         indent=2, ensure_ascii=False))
        return code

    if not profile.is_dir():
        return fail(f"preview profile not found: {profile}")
    if not plugin_root.is_dir():
        return fail(f"installed preview plugin not found: {plugin_root}")
    if out == preview_root or preview_root in out.parents:
        return fail(f"refusing an --out inside the preview root: {out}")

    exe = Path(args.freecad_exe) if args.freecad_exe else None
    if exe is None and launcher.get("freecad_exe"):
        exe = Path(launcher["freecad_exe"])
    if exe is None:
        exe = DEFAULT_FREECAD
    if not exe.is_file():
        return fail(f"FreeCAD executable not found: {exe}")

    user_cfg_src = profile / "user.cfg"
    system_cfg_src = profile / "system.cfg"
    if not user_cfg_src.is_file() or not system_cfg_src.is_file():
        return fail(f"preview configs missing: {user_cfg_src} / {system_cfg_src}")

    out.mkdir(parents=True, exist_ok=True)
    configs = out / "config"
    configs.mkdir(parents=True, exist_ok=True)
    work = out / "work"
    work.mkdir(parents=True, exist_ok=True)
    user_cfg = configs / "user.cfg"
    system_cfg = configs / "system.cfg"
    shutil.copyfile(user_cfg_src, user_cfg)
    shutil.copyfile(system_cfg_src, system_cfg)

    macro = out / MACRO_NAME
    macro.write_text(MACRO, encoding="utf-8")
    result_file = out / "verify_result.json"
    log_path = out / "startup.log"
    if result_file.exists():
        result_file.unlink()

    env = dict(os.environ)
    env["FREECAD_USER_HOME"] = str(profile)
    env["IBRA_V05_VERIFY_OUT"] = str(out)
    env["IBRA_V05_PREVIEW_ROOT"] = str(preview_root)
    env["IBRA_V05_PLUGIN_ROOT"] = str(plugin_root)
    env["IBRA_V05_TWO_PATCH"] = "1" if args.two_patch else "0"
    env["PYTHONIOENCODING"] = "utf-8"
    env["PYTHONUNBUFFERED"] = "1"

    process = run_freecad(exe, macro, user_cfg, system_cfg, env, out, result_file,
                          log_path, args.timeout)
    result = {}
    if result_file.is_file():
        try:
            result = json.loads(result_file.read_text(encoding="utf-8"))
        except Exception as error:  # noqa: BLE001 - reported as a malformed result
            result = {"error": f"unreadable result: {error}"}

    checks = result.get("checks", [])
    required = [entry for entry in checks if not entry.get("optional")]
    ok = (bool(result) and result.get("error") is None and bool(required)
          and all(entry.get("ok") for entry in required))
    tail = (log_path.read_text(encoding="utf-8", errors="replace").splitlines()[-40:]
            if log_path.is_file() else [])
    launcher_ok = launcher.get("exists") and (
        not launcher.get("freecad_exe") or Path(launcher["freecad_exe"]).resolve() == exe.resolve())

    summary = {
        "host_ok": ok,
        "preview_root": str(preview_root),
        "installed_plugin": str(plugin_root),
        "out": str(out),
        "freecad_exe": str(exe),
        "launcher": dict(launcher, exe_matches=launcher_ok),
        "configs": {"user": str(user_cfg), "system": str(system_cfg),
                    "cloned_from": [str(user_cfg_src), str(system_cfg_src)]},
        "macro": str(macro),
        "result_file": str(result_file),
        "startup_log": str(log_path),
        "process": process,
        "app_user_app_data_dir": result.get("app_user_app_data_dir"),
        "module_paths": result.get("module_paths", {}),
        "notes": result.get("notes", {}),
        "checks": checks,
        "startup_tail": tail,
        "error": result.get("error") or (None if process["result_seen"] else
                                         "the verification macro did not write a result"),
    }
    (out / "v05_preview_startup.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
